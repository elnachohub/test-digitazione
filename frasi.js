const FRASI = { it: FRASI_IT, en: FRASI_EN };

const ACCENTATE = /[àèéìíòóùú]/i;

/* Mescola una copia dell'elenco (algoritmo di Fisher-Yates: ogni ordine è ugualmente probabile). */
function mescola(elenco, caso) {
  const copia = [...elenco];
  for (let i = copia.length - 1; i > 0; i--) {
    const j = Math.floor(caso() * (i + 1));
    [copia[i], copia[j]] = [copia[j], copia[i]];
  }
  return copia;
}

// Un "sacchetto" di frasi mescolate per ogni combinazione livello/accenti:
// si pesca finché è vuoto, poi si rimescola. Così nessuna frase si ripete
// finché non sono uscite tutte le altre.
const sacchetti = {};

/*
 * Restituisce una frase.
 * opzioni.lingua: "it" | "en"
 * opzioni.livello: "facile" | "medio" | "difficile"
 * opzioni.punteggiatura: vero = frase così com'è; falso = tutto minuscolo,
 *   senza virgole e punti. L'apostrofo resta: fa parte della parola ("l'alba").
 * opzioni.accenti: vero = ammesse anche le frasi con lettere accentate.
 * caso: generatore di numeri in [0, 1); sostituibile nei test.
 */
function generaFrase(opzioni, caso = Math.random) {
  const { lingua = "it", livello = "medio", punteggiatura = true, accenti = false } = opzioni;
  const chiave = `${lingua}-${livello}-${accenti}`;
  if (!sacchetti[chiave] || sacchetti[chiave].length === 0) {
    const ammesse = FRASI[lingua][livello].filter((f) => accenti || !ACCENTATE.test(f));
    sacchetti[chiave] = mescola(ammesse, caso);
  }
  const frase = sacchetti[chiave].pop();
  if (punteggiatura) return frase;
  return frase.replace(/[,.]/g, "").toLowerCase();
}

