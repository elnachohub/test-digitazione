/* Traduce una chiave nella lingua data; se manca, ripiega sull'italiano e poi sulla chiave stessa. */
function traduci(lingua, chiave, valori = {}) {
  const testo = (TESTI[lingua] && TESTI[lingua][chiave]) ?? TESTI.it[chiave] ?? chiave;
  return testo.replace(/\{(\w+)\}/g, (_, nome) => (nome in valori ? valori[nome] : `{${nome}}`));
}

if (typeof module !== "undefined") module.exports = { TESTI, traduci };
